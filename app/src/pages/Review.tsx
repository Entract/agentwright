import { useEffect, useState } from 'react'
import { Link, Route, Routes } from 'react-router-dom'
import { db } from '../db/db'
import { useLive } from '../db/useLive'
import { PRIORITY_MISCONCEPTIONS, topicById, topics } from '../content'
import { ensureSeeded } from '../learn/store'
import { applyReview, describeInterval, dueCards, nextInterval, type Rating } from '../review/scheduler'
import type { ReviewCard } from '../types'

const SESSION_SIZE = 10

const SOURCE_LABEL: Record<ReviewCard['source'], string> = {
  conversation: 'From the original teaching conversation',
  practice: 'Added after a missed question in practice',
  generated: 'Generated by the AI tutor',
  manual: 'Written by you',
}

function dueText(card: ReviewCard, now: number): string {
  if (card.retired) return 'Retired'
  if (card.dueAt <= now) return 'Due now'
  const days = Math.ceil((card.dueAt - now) / (24 * 60 * 60 * 1000))
  return days <= 1 ? 'Due within a day' : `Due in ${days} days`
}

function ReviewSession() {
  const [queue, setQueue] = useState<ReviewCard[] | null>(null)
  const [index, setIndex] = useState(0)
  const [shown, setShown] = useState(false)
  const [note, setNote] = useState('')
  const [reviewed, setReviewed] = useState(0)
  const [sessionId, setSessionId] = useState<number | null>(null)
  const [totals, setTotals] = useState<{ due: number; next: number | null }>({ due: 0, next: null })

  async function load() {
    await ensureSeeded()
    const cards = await db.cards.toArray()
    const now = Date.now()
    const due = dueCards(cards, now, PRIORITY_MISCONCEPTIONS)
    const upcoming = cards.filter((c) => !c.retired && c.dueAt > now).map((c) => c.dueAt)
    setTotals({ due: due.length, next: upcoming.length ? Math.min(...upcoming) : null })
    setQueue(due.slice(0, SESSION_SIZE))
    setIndex(0)
    setShown(false)
    setNote('')
  }

  useEffect(() => {
    load()
  }, [])

  if (!queue) return <p className="muted">Loading…</p>

  const card = queue[index]

  async function rate(rating: Rating) {
    let id = sessionId
    if (id === null) {
      id = await db.sessions.add({ kind: 'review', startedAt: Date.now(), exerciseIds: [] })
      setSessionId(id)
    }
    await db.cards.put(applyReview(card, rating, Date.now(), note.trim() || undefined))
    await db.sessions.update(id, { endedAt: Date.now() })
    setReviewed(reviewed + 1)
    setShown(false)
    setNote('')
    setIndex(index + 1)
  }

  if (!card) {
    return (
      <>
        <h1>Review</h1>
        {reviewed > 0 ? (
          <div className="notice ok">
            {reviewed} card{reviewed > 1 ? 's' : ''} reviewed.
          </div>
        ) : null}
        {totals.due > queue.length && reviewed > 0 ? (
          <button className="primary" onClick={() => { setReviewed(0); load() }}>
            Review more
          </button>
        ) : (
          <p>
            Nothing is due right now.
            {totals.next ? ` The next card is due ${new Date(totals.next).toLocaleDateString(undefined, { weekday: 'long', day: 'numeric', month: 'short' })}.` : ''}
          </p>
        )}
        <p style={{ marginTop: 16 }}>
          <Link to="cards">All cards</Link>
        </p>
      </>
    )
  }

  const topic = topicById.get(card.topicId)
  return (
    <>
      <div className="row spread">
        <h1>Review</h1>
        <span className="muted">
          Card {index + 1} of {queue.length}
          {totals.due > queue.length ? ` (${totals.due} due)` : ''}
        </span>
      </div>
      <div className="card" data-testid="review-card">
        <div className="row" style={{ marginBottom: 8 }}>
          <span className="tag soft">{card.kind === 'oneliner' ? 'Write one line' : 'Recall'}</span>
          {topic && <span className="muted">{topic.title}</span>}
        </div>
        <p style={{ whiteSpace: 'pre-wrap', fontWeight: 600 }}>{card.front}</p>
        {!shown && (
          <>
            <label htmlFor="note">{card.kind === 'oneliner' ? 'Your line' : 'Your answer or reasoning (optional)'}</label>
            <textarea
              id="note"
              className={card.kind === 'oneliner' ? 'mono' : ''}
              rows={2}
              style={{ minHeight: 60 }}
              spellCheck={false}
              autoCapitalize="off"
              autoCorrect="off"
              value={note}
              onChange={(e) => setNote(e.target.value)}
            />
            <div className="row" style={{ marginTop: 10 }}>
              <button className="primary" onClick={() => setShown(true)}>
                Show answer
              </button>
            </div>
          </>
        )}
        {shown && (
          <>
            {note.trim() && (
              <>
                <div className="muted">You wrote</div>
                <pre className="code output">{note}</pre>
              </>
            )}
            <div className="muted">Answer</div>
            <pre className="code output">{card.back}</pre>
            <div className="muted" style={{ marginBottom: 6 }}>How did it go? Your choice sets when the card returns.</div>
            <div className="row">
              {(['again', 'hard', 'good'] as const).map((rating) => (
                <button key={rating} className={rating === 'good' ? 'primary' : ''} onClick={() => rate(rating)} style={{ flexDirection: 'column', lineHeight: 1.2 }}>
                  <span>{rating === 'again' ? 'Missed it' : rating === 'hard' ? 'Shaky' : 'Got it'}</span>
                  <span className="small" style={{ opacity: 0.75 }}>{describeInterval(nextInterval(card, rating).intervalDays)}</span>
                </button>
              ))}
            </div>
          </>
        )}
      </div>
      <p className="muted">
        {SOURCE_LABEL[card.source]}
        {card.edited ? ', edited by you' : ''}. Reviewed {card.history.length} time{card.history.length === 1 ? '' : 's'}.{' '}
        <Link to={`cards?edit=${encodeURIComponent(card.id)}`}>Edit or retire</Link>
      </p>
    </>
  )
}

function CardEditor({ card, onDone }: { card: ReviewCard | null; onDone: () => void }) {
  const [front, setFront] = useState(card?.front ?? '')
  const [back, setBack] = useState(card?.back ?? '')
  const [topicId, setTopicId] = useState(card?.topicId ?? 'g-write-function')

  async function save() {
    if (!front.trim() || !back.trim()) return
    if (card) await db.cards.update(card.id, { front, back, topicId, edited: true })
    else {
      await db.cards.add({
        id: `manual-${Date.now()}`, topicId, kind: 'recall', front, back, source: 'manual',
        dueAt: Date.now(), intervalDays: 0, step: 0, history: [], retired: false,
      })
    }
    onDone()
  }

  return (
    <div className="card">
      <strong>{card ? 'Edit card' : 'New card'}</strong>
      <label htmlFor="front">Question</label>
      <textarea id="front" rows={2} value={front} onChange={(e) => setFront(e.target.value)} />
      <label htmlFor="back">Answer</label>
      <textarea id="back" rows={3} value={back} onChange={(e) => setBack(e.target.value)} />
      <label htmlFor="topic">Topic</label>
      <select id="topic" value={topicId} onChange={(e) => setTopicId(e.target.value)}>
        {topics.map((t) => (
          <option key={t.id} value={t.id}>
            {t.module}. {t.title}
          </option>
        ))}
      </select>
      <div className="row" style={{ marginTop: 10 }}>
        <button className="primary" onClick={save} disabled={!front.trim() || !back.trim()}>
          Save
        </button>
        <button className="quiet" onClick={onDone}>
          Cancel
        </button>
        {card && (
          <button
            className="quiet"
            onClick={async () => {
              await db.cards.update(card.id, { retired: !card.retired })
              onDone()
            }}
          >
            {card.retired ? 'Bring back' : 'Retire card'}
          </button>
        )}
      </div>
    </div>
  )
}

function CardList() {
  const cards = useLive(() => db.cards.toArray())
  const initial = new URLSearchParams(window.location.hash.split('?')[1] ?? '').get('edit')
  const [editing, setEditing] = useState<string | 'new' | null>(initial)
  if (!cards) return <p className="muted">Loading…</p>
  const now = Date.now()
  const sorted = [...cards].sort((a, b) => Number(a.retired) - Number(b.retired) || a.dueAt - b.dueAt)
  return (
    <>
      <Link to="/review" className="link">‹ Review</Link>
      <div className="row spread">
        <h1>All cards</h1>
        <button className="quiet" onClick={() => setEditing('new')}>
          New card
        </button>
      </div>
      {editing === 'new' && <CardEditor card={null} onDone={() => setEditing(null)} />}
      {sorted.map((card) =>
        editing === card.id ? (
          <CardEditor key={card.id} card={card} onDone={() => setEditing(null)} />
        ) : (
          <div key={card.id} className="card" style={card.retired ? { opacity: 0.55 } : undefined}>
            <div style={{ fontWeight: 600 }}>{card.front}</div>
            <div className="muted">
              {dueText(card, now)} · {SOURCE_LABEL[card.source]}
              {card.edited ? ', edited' : ''} · reviewed {card.history.length}×
            </div>
            {card.history.length > 0 && (
              <details>
                <summary className="muted">Review history</summary>
                <ul className="small">
                  {card.history.map((h, i) => (
                    <li key={i}>
                      {new Date(h.ts).toLocaleDateString()}: {h.rating === 'again' ? 'missed' : h.rating === 'hard' ? 'shaky' : 'got it'}
                      {h.note ? ` — “${h.note}”` : ''}
                    </li>
                  ))}
                </ul>
              </details>
            )}
            <button className="quiet" style={{ minHeight: 36, padding: '4px 10px', marginTop: 6 }} onClick={() => setEditing(card.id)}>
              Edit
            </button>
          </div>
        ),
      )}
    </>
  )
}

export default function Review() {
  return (
    <section className="page">
      <Routes>
        <Route index element={<ReviewSession />} />
        <Route path="cards" element={<CardList />} />
      </Routes>
    </section>
  )
}
